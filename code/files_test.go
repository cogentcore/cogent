// region returns the region between the given lines and characters.
func region(stLn, stCh, edLn, edCh int) textpos.Region {
	return textpos.Region{Start: textpos.Pos{Line: stLn, Char: stCh}, End: textpos.Pos{Line: edLn, Char: edCh}}
}

// TestCodeFiles tests opening files in the editors of a project, saving,
// reverting, and closing them, and the open files.
func TestCodeFiles(t *testing.T) {
	tmp := tempDir(t)
	path := writeFiles(t, tmp, map[string]string{
		"a.txt":     "a text\n",
		"b.txt":     "b text\n",
		"sub/c.txt": "c text\n",
		"gen.go":    "// Code generated by test; DO NOT EDIT.\n//line src.go:1\npackage x\n",
		"src.go":    "package x\n",
	})
	b, cv := newTestCode(t, tmp)
	core.AssertRender(t, b, "files", func() {
		locked(b, func() {
			assert.True(t, cv.InRootPath(path("a.txt")))
			assert.False(t, cv.InRootPath("/elsewhere/a.txt"))

			tv, idx, ok := cv.ViewFile(core.Filename(path("a.txt")))
			require.True(t, ok)
			assert.Equal(t, 0, idx)
			assert.Equal(t, path("a.txt"), tv.Lines.Filename())
			assert.Same(t, tv.Lines, cv.ActiveLines())
			_, idx, _ = cv.ViewFile(core.Filename(path("a.txt")))
			assert.Equal(t, 0, idx, "already viewed")

			nv, nidx, ok := cv.NextViewFile(path("b.txt"))
			require.True(t, ok)
			assert.Equal(t, 1, nidx)
			assert.Equal(t, path("b.txt"), nv.Lines.Filename())
			_, _, ok = cv.NextViewFile("src.go") // found by name in the file tree
			assert.True(t, ok)
			_, _, ok = cv.NextViewFile("none.txt")
			assert.False(t, ok)

			_, nidx = cv.CloneActiveView()
			assert.GreaterOrEqual(t, nidx, 0)
			cv.SwapTextEditors()

			tv, idx, ok = cv.LinkViewFile(path("gen.go"))
			require.True(t, ok)
			assert.Equal(t, path("src.go"), tv.Lines.Filename(), "the source of the generated file")
			assert.Equal(t, 1, idx, "next to the tabs")
			_, err := cv.ShowFile(path("src.go"), 1)
			assert.NoError(t, err)
			_, err = cv.ShowFile(path("none.txt"), 1)
			assert.Error(t, err)
			_, _, ok = cv.ViewFileInIndex(path("none.txt"), 0)
			assert.False(t, ok)

			assert.Equal(t, 4, cv.OpenFiles.Len())
			assert.Contains(t, cv.OpenFiles.Strings(tmp), "a.txt")
			assert.Len(t, cv.OpenFiles.Paths(), 4)
			cv.OpenFiles.Move(0, 1)
			cv.OpenFiles.ReMarkup()
			cv.SelectOpenFile() // a menu
			assert.NotNil(t, cv.FileNodeForFile(path("a.txt")))
			assert.Nil(t, cv.FileNodeForFile(path("sub")), "a directory")
		})

		// edit, save, revert, and close
		locked(b, func() {
			cv.ViewFileInIndex(path("a.txt"), 0)
			tv := cv.ActiveEditor()
			ln := tv.Lines
			ln.InsertText(textpos.Pos{}, []rune("new "))
			assert.Equal(t, 1, cv.NChangedFiles())
			cv.SaveActiveView()
			assert.Equal(t, 0, cv.NChangedFiles())
			b, _ := os.ReadFile(path("a.txt"))
			assert.Equal(t, "new a text\n", string(b))

			ln.InsertText(textpos.Pos{}, []rune("x"))
			cv.RevertActiveView()
			assert.Equal(t, "new a text\n", ln.String())

			ln.InsertText(textpos.Pos{}, []rune("y"))
			cv.SaveAll()
			b, _ = os.ReadFile(path("a.txt"))
			assert.Equal(t, "ynew a text\n", string(b))

			cv.SaveActiveViewAs(core.Filename(path("a2.txt")))
			assert.FileExists(t, path("a2.txt"))
			assert.Nil(t, cv.GetOpenFile(path("a.txt")), "renamed")
			assert.NotNil(t, cv.GetOpenFile(path("a2.txt")))

			cv.CloseActiveView()
			assert.Nil(t, cv.GetOpenFile(path("a2.txt")))
			cv.CloseOpenFiles([]string{path("b.txt"), path("sub"), path("none.txt")})
			assert.Nil(t, cv.GetOpenFile(path("b.txt")))
		})

		// new files
		locked(b, func() {
			cv.NewFile("new.txt", false)
			assert.FileExists(t, path("new.txt"))
			cv.NewFile("new.txt", false) // exists: a dialog
		})
	})
}

// TestCodeEdits tests the editing commands of Code on the active editor.
func TestCodeEdits(t *testing.T) {
	tmp := tempDir(t)
	path := writeFiles(t, tmp, map[string]string{
		"a.go":   "package a\n\nfunc a() {\nx := 1\n}\n",
		"p.txt":  "one\ntwo\n\nthree\nfour\n",
		"t.txt":  "a\n\tx", // no newline at the end
		"b.txt":  "one\nthree\n",
		"w.txt":  "some words here\nmore\n",
		"r.txt":  "abc\ndef\n",
		"rc.txt": "hello world\n",
	})
	b, cv := newTestCode(t, tmp)
	core.AssertRender(t, b, "edits", func() {
		view := func(name string) (*TextEditor, *lines.Lines) {
			tv, _, ok := cv.ViewFileInIndex(path(name), 0)
			require.True(t, ok)
			tv.SelectReset()
			return tv, tv.Lines
		}
		locked(b, func() {
			tv, ln := view("a.go")
			tv.SetCursorShow(textpos.Pos{Line: 3})
			assert.True(t, cv.CommentOut())
			assert.Equal(t, "// x := 1", strings.TrimSpace(string(ln.Line(3))))
			tv.SelectRegion = region(3, 1, 3, 4) // within the line
			assert.True(t, cv.CommentOut(), "uncommented")
			assert.Equal(t, "x := 1", strings.TrimSpace(string(ln.Line(3))))

			assert.False(t, cv.Indent(), "no selection")
			cv.Settings.LangBackend = LangBackendParser // without a language server
			tv.SelectRegion = region(3, 0, 3, 2)
			assert.True(t, cv.Indent())
			cv.Settings.LangBackend = LangBackendLSP

			tv, _ = view("rc.txt")
			tv.SelectRegion = region(0, 0, 0, 11)
			assert.Equal(t, "HELLO WORLD", cv.ReCase(strcase.UpperCase))

			tv, ln = view("p.txt")
			cv.JoinParaLines()
			assert.Equal(t, "one two\n\nthree four\n", ln.String())
			tv.SelectRegion = region(0, 0, 0, 3)
			cv.JoinParaLines()

			tv, ln = view("t.txt")
			cv.TabsToSpaces()
			assert.Equal(t, "a\n    x\n", ln.String(), "including the last line")
			cv.SpacesToTabs()
			assert.Equal(t, "a\n\tx\n", ln.String())
			tv.SelectRegion = region(1, 0, 1, 2)
			cv.TabsToSpaces()
			assert.Equal(t, "a\n    x\n", ln.String(), "the selected line")
			tv.SelectRegion = region(0, 0, 1, 0)
			cv.SpacesToTabs()
			assert.Equal(t, "a\n    x\n", ln.String(), "not the line after the selection")

			tv, _ = view("w.txt")
			assert.Contains(t, cv.CountWords(), "Words: 4")
			assert.Contains(t, cv.CountWordsRegion(), "Words: 4", "the whole file without a selection")
			tv.SelectRegion = region(0, 5, 1, 2)
			assert.Contains(t, cv.CountWordsRegion(), "Words: 3")

			// rectangles and registers
			tv, ln = view("r.txt")
			tv.SelectRegion = region(0, 0, 1, 1)
			cv.CopyRect()
			tv.SetCursorShow(textpos.Pos{Line: 0, Char: 3})
			cv.PasteRect()
			assert.Equal(t, "abca\ndefd\n", ln.String())
			tv.SelectRegion = region(0, 0, 1, 1)
			cv.CutRect()
			assert.Equal(t, "bca\nefd\n", ln.String())

			tv.SelectRegion = region(0, 0, 0, 3)
			cv.RegisterCopy("r1: old text")
			assert.Equal(t, "bca", AvailableRegisters["r1"])
			assert.Equal(t, RegisterName("r1"), cv.Settings.Register)
			assert.Contains(t, AvailableRegisters.Names(), "r1: bca")
			cv.RegisterCopy("r2") // no selection: nothing
			_, has := AvailableRegisters["r2"]
			assert.False(t, has)

			cv.CursorToHistPrev()
			cv.CursorToHistNext()
			cv.ReplaceInActive() // a prompt

			cv.DiffFiles(core.Filename(path("b.txt")), core.Filename(path("p.txt")))
			cv.DiffFiles(core.Filename(path("none.txt")), core.Filename(path("p.txt")))
			lnb := cv.GetOpenFile(path("b.txt"))
			cv.DiffFileLines(lnb, path("none.txt"))
			diffs := cv.Tabs().TabByName("Diffs")
			require.NotNil(t, diffs)
		})
	})
}

// TestProjectPathParse tests parsing the paths of projects and finding
// their project files.
func TestProjectPathParse(t *testing.T) {
	tmp := tempDir(t)
	path := writeFiles(t, tmp, map[string]string{"proj/a.go": "package a\n"})
	root, pnm, fnm, ok := ProjectPathParse(path("proj"))
	assert.True(t, ok)
	assert.Equal(t, path("proj"), root)
	assert.Equal(t, "proj", pnm)
	assert.Equal(t, "", fnm)
	root, pnm, fnm, ok = ProjectPathParse(path("proj/a.go"))
	assert.True(t, ok)
	assert.Equal(t, path("proj"), root)
	assert.Equal(t, "proj", pnm)
	assert.Equal(t, "a.go", fnm)
	_, pnm, _, ok = ProjectPathParse("")
	assert.False(t, ok)
	assert.Equal(t, "blank", pnm)
	_, _, _, ok = ProjectPathParse(path("none"))
	assert.False(t, ok)

	_, has := CheckForProjectAtPath(path("proj"))
	assert.False(t, has)
	require.NoError(t, os.WriteFile(path("proj/proj.code"), nil, 0o644))
	pf, has := CheckForProjectAtPath(path("proj/a.go"))
	assert.True(t, has)
	assert.Equal(t, filepath.Join(path("proj"), "proj.code"), pf)
	_, has = CheckForProjectAtPath(path("none"))
	assert.False(t, has)
}
